import React from 'react';
import { useTranslation } from 'react-i18next';
import { useNavigate } from 'react-router-dom';
import { GraduationCap, Globe, MapPin, ArrowRight, Sparkles } from 'lucide-react';
import {
  useGetUniversityRecommendationsQuery,
  type UniversityRecommendation,
} from '../../../../app/services/student-hub/psychometricApi';

interface UniversityMatchesProps {
  /** Drives the AI university-recommendation call. */
  studentProfileId: string;
  maxDisplay?: number;
}

/** Two-letter monogram from a university name (no logos for world schools). */
const monogram = (name: string): string =>
  name
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => w[0])
    .slice(0, 2)
    .join('')
    .toUpperCase();

/** Map the model's Reach/Match/Safety label to a tag colour class. */
const typeClass = (type: string): string => {
  const t = type.toLowerCase();
  if (t.includes('safety')) return 'majormatch-results__tag--green';
  if (t.includes('reach')) return 'majormatch-results__tag--amber';
  return 'majormatch-results__tag--brand';
};

/**
 * AI Major Match → Universities tab.
 *
 * Best-fit universities are GENERATED BY AI (real schools worldwide, matched to
 * the student's profile and top majors) — not the TopCoach directory. The
 * "Browse all universities" CTA is the separate path into our own 100-school
 * directory.
 */
export const UniversityMatches: React.FC<UniversityMatchesProps> = ({
  studentProfileId,
  maxDisplay = 6,
}) => {
  const { t } = useTranslation();
  const navigate = useNavigate();

  const { data, isLoading, isError } = useGetUniversityRecommendationsQuery(studentProfileId, {
    skip: !studentProfileId,
  });

  const universities: UniversityRecommendation[] = Array.isArray(data?.universities)
    ? data!.universities.slice(0, maxDisplay)
    : [];

  const browseAll = (
    <div className="majormatch-results__cta-band">
      <p className="majormatch-results__cta-band-text">
        {t(
          'studentHub.psychometric.results.uni.browseAllText',
          'Browse the full TopCoach university directory to explore programs in detail.',
        )}
      </p>
      <button
        type="button"
        className="majormatch-results__btn majormatch-results__btn--primary"
        onClick={() => navigate('/universities')}
      >
        {t('studentHub.psychometric.results.uni.browseAll', 'Browse all universities')}
        <ArrowRight size={16} />
      </button>
    </div>
  );

  const header = (
    <>
      <h4 className="majormatch-results__card-title">
        <GraduationCap size={18} />
        {t('studentHub.psychometric.results.uni.title', 'University matches')}
      </h4>
      <p className="majormatch-results__card-sub">
        {t(
          'studentHub.psychometric.results.uni.subtitle',
          'AI-picked universities worldwide that fit your profile and top majors.',
        )}
      </p>
    </>
  );

  // — Loading ────────────────────────────────────────────────────────
  if (isLoading) {
    return (
      <div className="majormatch-results__card">
        {header}
        <div className="majormatch-results__loading">
          <span className="majormatch-results__spinner" />
          <div>
            <p className="majormatch-results__loading-title">
              {t('studentHub.psychometric.results.uni.loadingTitle', 'Finding your best-fit universities')}
            </p>
            <p className="majormatch-results__loading-text">
              {t(
                'studentHub.psychometric.results.uni.loadingText',
                'Our AI is matching universities to your interests, majors, and academic profile.',
              )}
            </p>
          </div>
        </div>
      </div>
    );
  }

  // — Error or empty (e.g. AI unavailable) → directory fallback ───────
  if (isError || universities.length === 0) {
    return (
      <div className="majormatch-results__card">
        {header}
        <div className="majormatch-results__notice">
          <p className="majormatch-results__notice-title">
            <Globe size={16} />
            {t(
              'studentHub.psychometric.results.uni.unavailableTitle',
              'University picks aren’t ready yet',
            )}
          </p>
          <p className="majormatch-results__notice-text">
            {t(
              'studentHub.psychometric.results.uni.unavailableText',
              'We couldn’t generate personalised university picks right now. You can still browse our full directory below.',
            )}
          </p>
        </div>
        {browseAll}
      </div>
    );
  }

  // — AI recommendations ──────────────────────────────────────────────
  return (
    <div className="majormatch-results__card">
      {header}

      <div className="majormatch-results__uni-grid">
        {universities.map((uni, i) => (
          <div key={`${uni.name}-${i}`} className="majormatch-results__uni-card">
            <div className="majormatch-results__uni-head">
              <span className="majormatch-results__uni-mono">{monogram(uni.name)}</span>
              <div style={{ flex: 1, minWidth: 0 }}>
                <div className="majormatch-results__uni-name">{uni.name}</div>
                <div className="majormatch-results__uni-meta">
                  {uni.country && (
                    <>
                      <MapPin size={11} style={{ verticalAlign: '-1px', marginRight: 3 }} />
                      {uni.country}
                    </>
                  )}
                  {uni.country && uni.ranking != null && ' • '}
                  {uni.ranking != null &&
                    t('studentHub.psychometric.results.uni.rank', 'Rank #{{rank}}', {
                      rank: uni.ranking,
                    })}
                </div>
              </div>
            </div>

            {uni.type && (
              <div className="majormatch-results__uni-section majormatch-results__uni-tags">
                <span className={`majormatch-results__tag ${typeClass(uni.type)}`}>{uni.type}</span>
              </div>
            )}

            {uni.whyItFits && (
              <p className="majormatch-results__uni-why">{uni.whyItFits}</p>
            )}

            {uni.programs.length > 0 && (
              <div className="majormatch-results__uni-section">
                <span className="majormatch-results__rec-block-label">
                  {t('studentHub.psychometric.results.uni.relevantPrograms', 'Relevant programs')}
                </span>
                <div className="majormatch-results__uni-tags">
                  {uni.programs.slice(0, 4).map((p) => (
                    <span key={p} className="majormatch-results__tag">
                      {p}
                    </span>
                  ))}
                </div>
              </div>
            )}
          </div>
        ))}
      </div>

      <p className="majormatch-results__uni-aigen">
        <Sparkles size={12} style={{ verticalAlign: '-1px', marginRight: 5 }} />
        {t('studentHub.psychometric.results.uni.aiGenerated', 'AI-generated suggestions — verify details before applying.')}
      </p>

      {browseAll}
    </div>
  );
};

export default UniversityMatches;
