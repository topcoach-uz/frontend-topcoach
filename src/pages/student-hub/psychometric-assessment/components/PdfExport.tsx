import React from 'react';
import { Button, message } from 'antd';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import FontAwesomeIcon from '../../../../components/common/icons/FontAwesomeIcon';
import type {
  PsychometricAssessment,
  RecommendationsResponse,
} from '../../../../app/services/student-hub/psychometricApi';

interface PdfExportProps {
  assessment: PsychometricAssessment;
  recommendations: RecommendationsResponse;
  studentName?: string;
}

// RIASEC dimension names
const RIASEC_NAMES: Record<string, string> = {
  realistic: 'Realistic',
  investigative: 'Investigative',
  artistic: 'Artistic',
  social: 'Social',
  enterprising: 'Enterprising',
  conventional: 'Conventional',
};

// Big Five trait names
const BIG_FIVE_NAMES: Record<string, string> = {
  openness: 'Openness',
  conscientiousness: 'Conscientiousness',
  extraversion: 'Extraversion',
  agreeableness: 'Agreeableness',
  neuroticism: 'Emotional Stability',
};

// Values names
const VALUES_NAMES: Record<string, string> = {
  achievement: 'Achievement',
  creativity: 'Creativity',
  helpingOthers: 'Helping Others',
  independence: 'Independence',
  security: 'Security',
  prestige: 'Prestige',
  workLifeBalance: 'Work-Life Balance',
  intellectualStimulation: 'Learning',
};

// Work style names
const WORK_STYLE_NAMES: Record<string, string> = {
  preferredEnvironment: 'Environment',
  collaborationStyle: 'Collaboration',
  pacePreference: 'Pace',
  leadershipTendency: 'Leadership',
  riskTolerance: 'Risk Tolerance',
};

export const PdfExport: React.FC<PdfExportProps> = ({
  assessment,
  recommendations,
  studentName = 'Student',
}) => {
  const generatePdf = () => {
    try {
      const doc = new jsPDF();
      const pageWidth = doc.internal.pageSize.getWidth();
      const pageHeight = doc.internal.pageSize.getHeight();
      const margin = 20;
      let yPos = 20;

      // Helper function to add footer
      const addFooter = (pageNum: number, totalPages: number) => {
        doc.setPage(pageNum);
        doc.setFontSize(8);
        doc.setTextColor(128, 128, 128);
        doc.text(
          `TopCoach Psychometric Assessment • Page ${pageNum} of ${totalPages}`,
          pageWidth / 2,
          pageHeight - 10,
          { align: 'center' }
        );
        doc.text(
          'Generated by TopCoach AI',
          pageWidth - margin,
          pageHeight - 10,
          { align: 'right' }
        );
      };

      // Helper function to check if new page is needed
      const checkNewPage = (requiredSpace: number = 15) => {
        if (yPos + requiredSpace > pageHeight - 30) {
          doc.addPage();
          yPos = 20;
          return true;
        }
        return false;
      };

      // ============================================
      // PAGE 1: COVER PAGE / OVERVIEW
      // ============================================
      
      // Header
      doc.setFillColor(139, 0, 0); // #8b0000
      doc.rect(0, 0, pageWidth, 50, 'F');
      
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(24);
      doc.setFont('helvetica', 'bold');
      doc.text('Psychometric Assessment Report', pageWidth / 2, 25, { align: 'center' });
      
      doc.setFontSize(12);
      doc.setFont('helvetica', 'normal');
      doc.text(`Generated for: ${studentName}`, pageWidth / 2, 38, { align: 'center' });
      doc.text(`Date: ${new Date().toLocaleDateString()}`, pageWidth / 2, 45, { align: 'center' });
      
      yPos = 60;
      doc.setTextColor(0, 0, 0);

      // RIASEC Code Section
      doc.setFontSize(18);
      doc.setFont('helvetica', 'bold');
      doc.text('Your RIASEC Code', margin, yPos);
      yPos += 10;

      doc.setFontSize(36);
      doc.setTextColor(139, 0, 0);
      doc.text(assessment.riasecCode, margin, yPos);
      yPos += 20;

      doc.setTextColor(0, 0, 0);
      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      
      // Quick Summary Box
      doc.setDrawColor(139, 0, 0);
      doc.setLineWidth(0.5);
      doc.rect(margin, yPos, pageWidth - margin * 2, 35);
      
      const topRecommendations = recommendations.recommendations.slice(0, 5);
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.text('Quick Summary', margin + 5, yPos + 8);
      
      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      doc.text(`${topRecommendations.length} Major Matches`, margin + 5, yPos + 16);
      doc.text(`Top Match: ${topRecommendations[0]?.fitScore.toFixed(0) || 0}%`, margin + 5, yPos + 22);
      doc.text(`Top Interest: ${recommendations.assessmentSummary.topInterests[0]?.dimension || 'N/A'}`, margin + 5, yPos + 28);
      doc.text(`Assessment Type: ${assessment.aptitudeScores ? 'With Aptitude' : 'Core Only'}`, margin + 100, yPos + 16);
      doc.text(`Questions Answered: ${assessment.assessmentMetadata?.questionCount || 'N/A'}`, margin + 100, yPos + 22);
      doc.text(`Completion Time: ${Math.round((assessment.assessmentMetadata?.completionTime || 0) / 60)} min`, margin + 100, yPos + 28);
      
      yPos += 45;

      // RIASEC Scores Table
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text('Interest Profile (RIASEC)', margin, yPos);
      yPos += 8;

      const riasecData = Object.entries(assessment.riasecScores)
        .sort((a, b) => b[1] - a[1])
        .map(([key, value]) => [RIASEC_NAMES[key], `${value.toFixed(0)}%`]);

      autoTable(doc, {
        startY: yPos,
        head: [['Dimension', 'Score']],
        body: riasecData,
        margin: { left: margin, right: margin },
        headStyles: { fillColor: [139, 0, 0], textColor: [255, 255, 255] },
        alternateRowStyles: { fillColor: [249, 250, 251] },
        styles: { fontSize: 10 },
      });

      yPos = (doc as any).lastAutoTable.finalY + 15;
      checkNewPage(30);

      // Values Scores
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text('Values & Motivations', margin, yPos);
      yPos += 8;

      const valuesData = Object.entries(assessment.valuesScores)
        .filter(([_, value]) => value > 0)
        .sort((a, b) => b[1] - a[1])
        .map(([key, value]) => [VALUES_NAMES[key] || key, `${value.toFixed(0)}%`]);

      autoTable(doc, {
        startY: yPos,
        head: [['Value', 'Score']],
        body: valuesData,
        margin: { left: margin, right: margin },
        headStyles: { fillColor: [236, 72, 153], textColor: [255, 255, 255] },
        alternateRowStyles: { fillColor: [249, 250, 251] },
        styles: { fontSize: 10 },
      });

      yPos = (doc as any).lastAutoTable.finalY + 15;

      // ============================================
      // PAGE 2: PERSONALITY (Big Five + Work Style)
      // ============================================
      
      doc.addPage();
      yPos = 20;

      // Page Header
      doc.setFillColor(99, 102, 241); // #6366f1
      doc.rect(0, 0, pageWidth, 30, 'F');
      
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(20);
      doc.setFont('helvetica', 'bold');
      doc.text('Personality Profile', pageWidth / 2, 18, { align: 'center' });
      
      yPos = 40;
      doc.setTextColor(0, 0, 0);

      // Big Five Scores
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text('Big Five Personality Traits', margin, yPos);
      yPos += 8;

      const bigFiveData = Object.entries(assessment.bigFiveScores).map(([key, value]) => {
        const displayValue = key === 'neuroticism' ? 100 - value : value;
        return [BIG_FIVE_NAMES[key], `${displayValue.toFixed(0)}%`];
      });

      autoTable(doc, {
        startY: yPos,
        head: [['Trait', 'Score']],
        body: bigFiveData,
        margin: { left: margin, right: margin },
        headStyles: { fillColor: [99, 102, 241], textColor: [255, 255, 255] },
        alternateRowStyles: { fillColor: [249, 250, 251] },
        styles: { fontSize: 10 },
      });

      yPos = (doc as any).lastAutoTable.finalY + 15;
      checkNewPage(40);

      // Work Style Profile
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text('Work Style Profile', margin, yPos);
      yPos += 8;

      const workStyleData = [
        ['Environment', assessment.workStyleProfile.preferredEnvironment || 'N/A'],
        ['Collaboration', assessment.workStyleProfile.collaborationStyle || 'N/A'],
        ['Pace', assessment.workStyleProfile.pacePreference || 'N/A'],
        ['Leadership Tendency', `${assessment.workStyleProfile.leadershipTendency || 0}%`],
        ['Risk Tolerance', `${assessment.workStyleProfile.riskTolerance || 0}%`],
      ];

      autoTable(doc, {
        startY: yPos,
        head: [['Aspect', 'Value']],
        body: workStyleData,
        margin: { left: margin, right: margin },
        headStyles: { fillColor: [245, 158, 11], textColor: [255, 255, 255] },
        alternateRowStyles: { fillColor: [249, 250, 251] },
        styles: { fontSize: 10 },
      });

      yPos = (doc as any).lastAutoTable.finalY + 15;

      // ============================================
      // PAGE 3+: MAJOR RECOMMENDATIONS
      // ============================================
      
      doc.addPage();
      yPos = 20;

      // Page Header
      doc.setFillColor(139, 0, 0);
      doc.rect(0, 0, pageWidth, 30, 'F');
      
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(20);
      doc.setFont('helvetica', 'bold');
      doc.text('Major Recommendations', pageWidth / 2, 18, { align: 'center' });
      
      yPos = 40;
      doc.setTextColor(0, 0, 0);

      // Top Recommendations
      const topRecs = recommendations.recommendations.slice(0, 5);
      
      topRecs.forEach((rec, index) => {
        checkNewPage(80);

        // Major name and fit score
        doc.setFontSize(14);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(139, 0, 0);
        doc.text(`${index + 1}. ${rec.majorName}`, margin, yPos);
        
        doc.setTextColor(16, 185, 129); // Green
        doc.text(`${rec.fitScore.toFixed(0)}% Match`, pageWidth - margin, yPos, { align: 'right' });
        yPos += 8;

        // Why it fits
        doc.setFontSize(10);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(0, 0, 0);
        
        if (rec.explanation?.whyFits) {
          doc.setFont('helvetica', 'bold');
          doc.text('Why it fits:', margin, yPos);
          yPos += 5;
          
          doc.setFont('helvetica', 'normal');
          const whyFitsLines = doc.splitTextToSize(rec.explanation.whyFits, pageWidth - margin * 2);
          doc.text(whyFitsLines, margin, yPos);
          yPos += whyFitsLines.length * 5 + 5;
        }

        // Key contributors (with null check)
        if (rec.explanation?.keyContributors && rec.explanation.keyContributors.length > 0) {
          checkNewPage(15);
          doc.setFont('helvetica', 'bold');
          doc.text('Key Contributors:', margin, yPos);
          yPos += 5;
          doc.setFont('helvetica', 'normal');
          const contributorsText = rec.explanation.keyContributors.join(', ');
          const contributorsLines = doc.splitTextToSize(contributorsText, pageWidth - margin * 2 - 50);
          doc.text(contributorsLines, margin + 50, yPos);
          yPos += contributorsLines.length * 5 + 5;
        }

        // Academic feasibility
        if (rec.explanation?.academicFeasibility) {
          checkNewPage(15);
          doc.setFont('helvetica', 'bold');
          doc.text('Academic Feasibility:', margin, yPos);
          yPos += 5;
          doc.setFont('helvetica', 'normal');
          const feasibilityLines = doc.splitTextToSize(rec.explanation.academicFeasibility, pageWidth - margin * 2);
          doc.text(feasibilityLines, margin, yPos);
          yPos += feasibilityLines.length * 5 + 5;
        }

        // Next steps
        if (rec.explanation?.nextSteps && rec.explanation.nextSteps.length > 0) {
          checkNewPage(rec.explanation.nextSteps.length * 5 + 10);
          doc.setFont('helvetica', 'bold');
          doc.text('Suggested Next Steps:', margin, yPos);
          yPos += 5;
          doc.setFont('helvetica', 'normal');
          rec.explanation.nextSteps.forEach((step) => {
            const stepLines = doc.splitTextToSize(`• ${step}`, pageWidth - margin * 2 - 10);
            doc.text(stepLines, margin + 5, yPos);
            yPos += stepLines.length * 5;
          });
        }

        yPos += 10; // Space between recommendations
      });

      // Add footer to recommendations page(s) - will be added in final loop

      // ============================================
      // FINAL PAGE: UNIVERSITY MATCHES (if applicable)
      // ============================================
      
      doc.addPage();
      yPos = 20;

      // Page Header
      doc.setFillColor(16, 185, 129); // Green
      doc.rect(0, 0, pageWidth, 30, 'F');
      
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(20);
      doc.setFont('helvetica', 'bold');
      doc.text('University Matches', pageWidth / 2, 18, { align: 'center' });
      
      yPos = 40;
      doc.setTextColor(0, 0, 0);

      doc.setFontSize(11);
      doc.setFont('helvetica', 'normal');
      doc.text('University recommendations are available in your online dashboard.', margin, yPos);
      doc.text('Visit the Universities tab in your assessment results for detailed matches.', margin, yPos + 7);

      // Add footer to all pages
      const totalPages = (doc as any).internal.getNumberOfPages();
      for (let i = 1; i <= totalPages; i++) {
        doc.setPage(i);
        addFooter(i, totalPages);
      }

      // Save PDF
      const filename = `psychometric-report-${new Date().toISOString().split('T')[0]}.pdf`;
      doc.save(filename);
      message.success('PDF exported successfully!');
    } catch (error) {
      console.error('Error generating PDF:', error);
      message.error('Failed to generate PDF. Please try again.');
    }
  };

  return (
    <Button size="large" onClick={generatePdf}>
      <FontAwesomeIcon icon="file-pdf" style={{ marginRight: 8 }} />
      Download PDF Report
    </Button>
  );
};

export default PdfExport;
